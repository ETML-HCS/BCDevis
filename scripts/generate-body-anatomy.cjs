function parseParts(filePath) {
  const source = fs.readFileSync(filePath, "utf8");
  const parts = {};
  const partPattern = /\{\s*slug:\s*"([^"]+)"[\s\S]*?path:\s*\{([\s\S]*?)\n\s*\},\s*\n\s*\},/g;
  let match;
  while ((match = partPattern.exec(source))) {
    parts[match[1]] = [...match[2].matchAll(/"([^"]+)"/g)].map((pathMatch) => pathMatch[1]);
  }
  return parts;
}

function extractOutline(filePath, label) {
  const source = fs.readFileSync(filePath, "utf8");
  const pattern = new RegExp(`d="([^"]+)"\\s+accessible=\\{true\\}\\s+accessibilityLabel="${label}"`);
  const match = source.match(pattern);
  if (!match) throw new Error(`Contour introuvable : ${label}`);
  return match[1];
}

function buildView(model, side, definition) {
  const parts = parseParts(path.join(sourceAssets, definition.asset));
  const regions = Object.fromEntries(Object.entries(groups[side]).map(([region, slugs]) => {
    const paths = slugs.flatMap((slug) => parts[slug] || []);
    if (!paths.length) throw new Error(`Aucun tracé pour ${model}/${side}/${region}`);
    return [region, paths];
  }));
  return {
    viewBox: definition.viewBox,
    outline: extractOutline(path.join(sourceComponents, definition.wrapper), definition.outlineLabel),
    focus: definition.focus,
    regions
  };
}

const anatomy = Object.fromEntries(Object.entries(sources).map(([model, sides]) => [
  model,
  Object.fromEntries(Object.entries(sides).map(([side, definition]) => [
    side,
    buildView(model, side, definition)
  ]))
]));

